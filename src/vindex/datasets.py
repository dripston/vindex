"""
Benchmark datasets for calibrated_similarity and indic_judge (v0.5.0).

WHY THIS EXISTS: calibrated_similarity's shipped calibration table and
indic_judge's human-agreement study (README.md's "argument for
calibrated_similarity" and its Limitations section) are both backed by
real, labeled data -- but a caller had no way to run that same data
through THEIR OWN encoder or judge model to check whether it works for
them too. They could only trust this project's own numbers or build a
labeled dataset from scratch. These two loaders ship the same data
these claims are based on, so a caller can verify instead of trust.

load_similarity_benchmark() -- 89 cases (10 questions x 3 languages x
{correct, wrong_subtle, wrong_hard}, minus a few languages/labels
without a case) used to compute README.md's AUC table. Deduplicated to
be encoder-independent: the original discrimination_per_case.csv has
one row per (encoder, case) since it was generated by sweeping 5
encoders over the same cases -- this ships just the cases, so you
bring your own encoder(s) and compute your own AUC via
vindex.calibrate(), rather than re-running this project's sweep.
gold_mode is fixed to "english_gold" (the slice README.md's own table
uses -- see calibration.py's module docstring for why this slice, not
"same_language_gold").

load_judge_benchmark() -- the same 62 traces used for the Milestone 6.3
human-agreement study, each with both independent human graders'
verdicts and which 19 were the untouched 30% holdout. Run indic_judge
(with any judge= you like) over these questions/answers and compare
its verdict to human_verdict_grader1/human_verdict_grader2_independent
to get your own agreement number for your own judge model -- instead
of trusting this project's 90.3% figure for openai/gpt-oss-120b, which
may not generalize to a different judge.

DISCLOSURE THIS DATA CARRIES (see docs/annotation/BIAS_PROTOCOL.md):
grader1 is this project's own owner, who also built indic_judge --
a real conflict of interest, mitigated by (not eliminated by) a frozen
rubric, blind grading sheet, and untouched 30% holdout. grader2 is an
independent fluent Hindi speaker with no stake in the result. Do not
report agreement against grader1 alone without this disclosure.
"""

from __future__ import annotations

import csv
import json
from collections.abc import Callable
from dataclasses import dataclass
from importlib import resources
from typing import Literal

_PACKAGE_DATA = "vindex.data.benchmarks"
_SIMILARITY_FILENAME = "similarity_benchmark.csv"
_JUDGE_FILENAME = "judge_benchmark.json"


@dataclass(frozen=True, slots=True)
class SimilarityBenchmarkCase:
    """case_id   : unique id, e.g. "capital_maharashtra__hi__wrong_hard".
    task_id   : the underlying question id shared across its
                language/label variants, e.g. "capital_maharashtra".
    language  : "en", "hi", or "hinglish".
    label     : "correct", "wrong_subtle", or "wrong_hard" -- ground
                truth for AUC/accuracy scoring, not a vindex verdict.
    gold_text : the short reference answer (English) this case's
                answer is judged against.
    answer    : the candidate answer to score.
    """

    case_id: str
    task_id: str
    language: str
    label: Literal["correct", "wrong_subtle", "wrong_hard"]
    gold_text: str
    answer: str


@dataclass(frozen=True, slots=True)
class JudgeBenchmarkTrace:
    """trace_id                          : e.g. "T001".
    question, answer                  : the QA pair a judge grades.
    trap_word                         : the ambiguous term this trace
                                         was built around (may or may
                                         not appear verbatim in answer).
    correct_meaning, wrong_meaning    : trap_word's two readings.
    ground_truth_answer_type          : "correct" or "wrong" -- this
                                         trace's actual construction,
                                         independent of any grader.
    human_verdict_grader1             : "correct" or "wrong" from this
                                         project's own owner (see this
                                         module's docstring disclosure).
    human_verdict_grader2_independent : "correct" or "wrong" from an
                                         independent fluent Hindi
                                         speaker with no stake.
    is_holdout                        : True for the 19 traces (30.6%)
                                         neither grader looked at until
                                         after both full gradings were
                                         submitted -- see
                                         docs/annotation/BIAS_PROTOCOL.md.
    """

    trace_id: str
    question: str
    answer: str
    trap_word: str
    correct_meaning: str
    wrong_meaning: str
    ground_truth_answer_type: Literal["correct", "wrong"]
    human_verdict_grader1: Literal["correct", "wrong"]
    human_verdict_grader2_independent: Literal["correct", "wrong"]
    is_holdout: bool


def similarity_benchmark_for_calibration(
    cases: list[SimilarityBenchmarkCase],
    score_fn: Callable[[str, str], float],
    *,
    language: str | None = None,
) -> tuple[list[float], list[float]]:
    """Score `cases` with your own `score_fn(gold_text, answer) -> float`
    (e.g. your own encoder's cosine similarity) and bucket the results
    into (similarities_correct, similarities_wrong) -- exactly the two
    lists vindex.calibrate() takes, so you can fit and inspect your own
    threshold/AUC on the same cases README.md's table is built from:

        from vindex.datasets import load_similarity_benchmark, similarity_benchmark_for_calibration
        from vindex.calibration import calibrate

        cases = load_similarity_benchmark()
        correct, wrong = similarity_benchmark_for_calibration(
            cases, my_cosine_similarity_fn, language="hi"
        )
        result = calibrate(correct, wrong)
        print(result.roc_auc)  # None -- calibrate() doesn't compute AUC
                                # itself; see calibrate()'s own docstring.

    "wrong_subtle" and "wrong_hard" are both bucketed as wrong -- pass
    language= to restrict to one of "en"/"hi"/"hinglish"; omit it to
    pool all three (not what README.md's own per-language table does,
    but a valid choice if that's what your use case needs).
    """
    correct = []
    wrong = []
    for case in cases:
        if language is not None and case.language != language:
            continue
        score = score_fn(case.gold_text, case.answer)
        if case.label == "correct":
            correct.append(score)
        else:
            wrong.append(score)
    return correct, wrong


def load_similarity_benchmark() -> list[SimilarityBenchmarkCase]:
    """89 (question, language, label, answer) cases used to compute
    README.md's calibrated_similarity AUC table -- see this module's
    docstring for what to do with them (run your own encoder, compute
    your own AUC via vindex.calibrate(), instead of trusting the
    shipped table for an encoder/language it wasn't measured on).
    """
    text = resources.files(_PACKAGE_DATA).joinpath(_SIMILARITY_FILENAME).read_text(
        encoding="utf-8"
    )
    reader = csv.DictReader(text.splitlines())
    return [
        SimilarityBenchmarkCase(
            case_id=row["case_id"],
            task_id=row["task_id"],
            language=row["language"],
            label=row["label"],  # type: ignore[arg-type]
            gold_text=row["gold_text"],
            answer=row["answer"],
        )
        for row in reader
    ]


def load_judge_benchmark() -> list[JudgeBenchmarkTrace]:
    """62 traces used for the Milestone 6.3 indic_judge human-agreement
    study -- see this module's docstring for what to do with them (run
    indic_judge, or any judge you like, and compare its verdict against
    human_verdict_grader1/human_verdict_grader2_independent) and for
    the bias disclosure this data carries.
    """
    text = resources.files(_PACKAGE_DATA).joinpath(_JUDGE_FILENAME).read_text(
        encoding="utf-8"
    )
    rows = json.loads(text)
    return [
        JudgeBenchmarkTrace(
            trace_id=row["trace_id"],
            question=row["question"],
            answer=row["answer"],
            trap_word=row["trap_word"],
            correct_meaning=row["correct_meaning"],
            wrong_meaning=row["wrong_meaning"],
            ground_truth_answer_type=row["ground_truth_answer_type"],
            human_verdict_grader1=row["human_verdict_grader1"],
            human_verdict_grader2_independent=row["human_verdict_grader2_independent"],
            is_holdout=row["is_holdout"],
        )
        for row in rows
    ]


@dataclass(frozen=True, slots=True)
class JudgeAgreementReport:
    """Result of scoring a judge callback against load_judge_benchmark().

    n                : traces actually scored (== len(traces) unless
                       only_holdout=True).
    agreement_grader1, agreement_grader2 : fraction of scored traces
                       where your judge's verdict matched that human
                       grader's verdict.
    disagreements    : trace_ids where your judge disagreed with EITHER
                       human grader -- inspect these first; this is
                       usually a much shorter list than n and is where
                       the actual signal is (see README.md's own
                       Limitations entry on the 4-trace disagreement
                       breakdown for indic_judge's own run, as an
                       example of what to look for: is your judge
                       wrong, or is it being appropriately strict about
                       something the rubric didn't anticipate?).
    """

    n: int
    agreement_grader1: float
    agreement_grader2: float
    disagreements: tuple[str, ...]


def score_judge_benchmark(
    judge_verdict: Callable[[JudgeBenchmarkTrace], Literal["correct", "wrong"]],
    *,
    only_holdout: bool = False,
) -> JudgeAgreementReport:
    """Run `judge_verdict` over load_judge_benchmark() and report
    agreement with both human graders -- the same comparison
    README.md's Milestone 6.3 study reports for indic_judge with
    openai/gpt-oss-120b (90.3%/56 of 62), so you can get the equivalent
    number for your own judge model or prompt instead of assuming this
    project's number carries over.

    judge_verdict receives one JudgeBenchmarkTrace and must return
    "correct" or "wrong" -- e.g., for indic_judge itself:

        from vindex import indic_judge
        from vindex.datasets import score_judge_benchmark

        def verdict(trace):
            r = indic_judge(trace.question, trace.answer)
            return "correct" if r.passed else "wrong"

        report = score_judge_benchmark(verdict)

    only_holdout=True scores only the 19 traces (30.6%) neither human
    grader looked at until after both full gradings were submitted --
    use this if you want a number that mirrors the holdout check
    README.md cites (94.7% for indic_judge's own run), not the full 62.

    Does not call any LLM itself -- judge_verdict is your own callback,
    so this works with indic_judge, a different judge model entirely,
    or a non-LLM heuristic you want to benchmark the same way.
    """
    traces = load_judge_benchmark()
    if only_holdout:
        traces = [t for t in traces if t.is_holdout]

    disagreements = []
    matches_g1 = 0
    matches_g2 = 0
    for trace in traces:
        verdict = judge_verdict(trace)
        if verdict == trace.human_verdict_grader1:
            matches_g1 += 1
        if verdict == trace.human_verdict_grader2_independent:
            matches_g2 += 1
        disagrees_g1 = verdict != trace.human_verdict_grader1
        disagrees_g2 = verdict != trace.human_verdict_grader2_independent
        if disagrees_g1 or disagrees_g2:
            disagreements.append(trace.trace_id)

    n = len(traces)
    return JudgeAgreementReport(
        n=n,
        agreement_grader1=matches_g1 / n if n else 0.0,
        agreement_grader2=matches_g2 / n if n else 0.0,
        disagreements=tuple(disagreements),
    )
